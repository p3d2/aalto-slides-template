#!/usr/bin/env python3
"""Turn the Aalto design tokens (tokens/design-tokens*.json, extracted from the
brand.aalto.fi JS bundle) into

  notes/design-tokens.md      human-readable digest (all tokens, refs resolved)
  ../../theme/tokens.typ      generated Typst constants imported by theme/aalto.typ

Offline, re-runnable. 1rem = 16px, 1px = 0.75pt.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
base = json.load(open(os.path.join(HERE, 'tokens', 'design-tokens.json')))
alias = json.load(open(os.path.join(HERE, 'tokens', 'design-tokens-1.json')))

def get(dotted):
    """Resolve '{base.color.neutral.9}' / '{alias.typography.title.h1}' style refs."""
    assert dotted.startswith('{') and dotted.endswith('}'), dotted
    parts = dotted[1:-1].split('.')
    root = {'base': base, 'alias': alias}[parts[0]]
    node = root
    for p in parts[1:]:
        if isinstance(node, dict) and p in node:
            node = node[p]
        else:
            return dotted
        if isinstance(node, dict) and '$value' in node and len(node) == 1:
            node = node['$value']
    if isinstance(node, dict) and '$value' in node:
        node = node['$value']
    return resolve(node) if isinstance(node, str) and node.startswith('{') else node

def resolve(v):
    if isinstance(v, str) and v.startswith('{'):
        return get(v)
    return v

def px(v):
    """'0.875rem' / '24px' / '-1px' -> float px."""
    if isinstance(v, (int, float)):
        return float(v)
    m = re.match(r'^\s*(-?[\d.]+)(rem|px|pt)?\s*$', str(v))
    if not m:
        return None
    n, unit = float(m.group(1)), (m.group(2) or 'px')
    return n * 16 if unit == 'rem' else (n * 16 / 12 if unit == 'pt' else n)

def pt(v):
    p = px(v)
    return None if p is None else round(p * 0.75, 2)

def strip(d):
    return {k: v for k, v in d.items() if not k.startswith('$')}

# ── colours ──────────────────────────────────────────────────────────────────
bc, sc, neutral, tint = {}, {}, {}, {}
for k, v in strip(base['color']['aaltoBrand']).items():
    bc[k] = resolve(v['$value'])
for k, v in strip(base['color']['school']).items():
    sc[k] = resolve(v['$value'])
for k, v in strip(base['color']['neutral']).items():
    neutral[k] = resolve(v['$value'])
for k, v in strip(base['color']['tint']).items():
    tint[k] = resolve(v['$value'])

# ── atomic type scale ────────────────────────────────────────────────────────
fs = {k: resolve(v['$value']) for k, v in strip(base['fontSize']).items()}
lh = {k: resolve(v['$value']) for k, v in strip(base['lineHeight']).items()}
ls = {k: resolve(v['$value']) for k, v in strip(base['letterSpacing']).items()}
wt = {k: resolve(v['$value']) for k, v in strip(base['fontWeight']).items()}
psp = {k: resolve(v['$value']) for k, v in strip(base['paragraphSpacing']).items()}
dim = {k: resolve(v['$value']) for k, v in strip(base['dimension']).items()}

# ── composite typography styles (mobile + desktop) ───────────────────────────
def style(val, ext=None):
    d = {k: get(v) if isinstance(v, str) else v for k, v in val.items()}
    out = {'weight': 'bold' if 'Bold' in str(d.get('fontWeight')) else 'regular',
           'size-pt': pt(d.get('fontSize')), 'leading-pt': pt(d.get('lineHeight')),
           'tracking-pt': pt(d.get('letterSpacing')),
           'size-px': px(d.get('fontSize')), 'leading-px': px(d.get('lineHeight'))}
    if ext:
        e = {k: get(v) if isinstance(v, str) else v for k, v in ext.items()}
        out['desktop'] = {'size-pt': pt(e.get('fontSize', d.get('fontSize'))),
                          'leading-pt': pt(e.get('lineHeight', d.get('lineHeight'))),
                          'tracking-pt': pt(e.get('letterSpacing', d.get('letterSpacing'))),
                          'size-px': px(e.get('fontSize', d.get('fontSize')))}
    return out

typo = {}
for group in ('title', 'body', 'icon'):
    typo[group] = {}
    for name, node in strip(alias['typography'][group]).items():
        ext = (node.get('$extensions') or {}).get('media:desktop')
        typo[group][name] = style(node['$value'], ext)

# ── markdown digest ──────────────────────────────────────────────────────────
M = ['# Aalto design tokens (brand.aalto.fi)', '',
     'Generated by `build_tokens.py` from `tokens/design-tokens.json` (atomic, "base")',
     'and `tokens/design-tokens-1.json` (semantic, "alias"), extracted from the site JS',
     'bundle `site/assets/tokens-CiGcZF1C.js`. Values are the official ones;',
     'px→pt uses 1px = 0.75pt, rem→px uses 1rem = 16px.', '',
     '## Fonts', '',
     '| Role | Family | Weights |', '|---|---|---|',
     f"| primary | {base['fontFamily']['primary']['$value']} | Regular, Bold |",
     f"| secondary (serif) | {base['fontFamily']['secondary']['$value']} | Regular, Bold |",
     f"| code | {base['fontFamily']['code']['$value']} | Regular |", '',
     '## Atomic scales', '',
     '| Token | px | pt |', '|---|---|---|']
for k in sorted(fs, key=lambda x: int(x)):
    M.append(f'| fontSize.{k} | {px(fs[k]):g} | {pt(fs[k]):g} |')
for k in sorted(lh, key=lambda x: int(x)):
    M.append(f'| lineHeight.{k} | {px(lh[k]):g} | {pt(lh[k]):g} |')
for k in sorted(ls, key=lambda x: int(x)):
    M.append(f'| letterSpacing.{k} | {px(ls[k]):g} | {pt(ls[k]):g} |')
for k in sorted(psp, key=lambda x: int(x)):
    M.append(f'| paragraphSpacing.{k} | {px(psp[k]):g} | {pt(psp[k]):g} |')
M += ['', '| Spacing token | px | pt |', '|---|---|---|']
for k in sorted(dim, key=lambda x: int(x)):
    M.append(f'| dimension.{k} | {px(dim[k]):g} | {pt(dim[k]):g} |')

M += ['', '## Composite type styles', '',
      '| Style | mobile size/leading (pt) | desktop size/leading (pt) | tracking (pt) | weight |',
      '|---|---|---|---|---|']
for group in ('title', 'body'):
    for name, s in typo[group].items():
        d = s.get('desktop')
        dstr = f"{d['size-pt']:g} / {d['leading-pt']:g}" if d else '—'
        M.append(f"| {group}.{name} | {s['size-pt']:g} / {s['leading-pt']:g} | {dstr} "
                 f"| {s['tracking-pt']:g} | {s['weight']} |")

M += ['', '> Brand rule (pages/brand/visual-guidelines/type.md): **max three type sizes',
      '> on any one visual surface**, titles larger than body, left-aligned ragged-right,',
      '> no ALL CAPS, no per-word capitalisation, headlines in Inter Bold with tight tracking.', '',
      '## Colour', '', '### Brand (university)', '', '| Token | HEX |', '|---|---|']
for k, v in bc.items():
    M.append(f'| {k} | {v} |')
M += ['', '### Schools', '', '| Token | HEX |', '|---|---|']
for k, v in sc.items():
    M.append(f'| {k} | {v} |')
M += ['', '### Neutral', '', '| Token | HEX | Note |', '|---|---|---|']
notes = {'1': 'white', '8': 'the design system\'s "black"', '9': 'pure black (brand black)',
         '5': 'secondary text on light', '4': 'light surface / foreground-tint on dark'}
for k, v in neutral.items():
    M.append(f'| neutral.{k} | {v} | {notes.get(k, "")} |')
M += ['', '### Tints (darker variants for hover/contrast on brand colours)', '',
      '| Token | HEX |', '|---|---|']
for k, v in tint.items():
    M.append(f'| {k} | {v} |')

M += ['', '## Layout', '', '| Token | Value |', '|---|---|']
for k, v in strip(base['screen']).items():
    M.append(f'| breakpoint.{k} | {resolve(v["$value"])} |')
for k, v in strip(base['columns']).items():
    M.append(f'| columns.{k} | {resolve(v["$value"])} |')
for k, v in strip(base['aspect']).items():
    M.append(f'| aspect.{k} | {resolve(v["$value"])} |')
M += ['', f"Icon glyphs available: {len(strip(base['icon']))} (see `tokens/design-tokens.json → icon`).", '']
os.makedirs(os.path.join(HERE, 'notes'), exist_ok=True)
open(os.path.join(HERE, 'notes', 'design-tokens.md'), 'w').write('\n'.join(M))

# ── generated Typst tokens ───────────────────────────────────────────────────
def col(v):
    return f'rgb("{v}")' if isinstance(v, str) and v.startswith('#') else str(v)

T = ['// ─────────────────────────────────────────────────────────────────────────────',
     '// GENERATED FILE — do not edit by hand.',
     '// Aalto design tokens as Typst constants, produced from the official brand',
     '// library tokens (brand.aalto.fi) by',
     '//   reference/brand-aalto-fi/build_tokens.py',
     '// Source: reference/brand-aalto-fi/tokens/design-tokens*.json',
     '// px→pt at 1px = 0.75pt. See reference/brand-aalto-fi/notes/design-tokens.md.',
     '// ─────────────────────────────────────────────────────────────────────────────',
     '', '// Brand (university) colours', '#let brand-colours = (']
for k, v in bc.items():
    T.append(f'  {k}: {col(v)},')
T += [')', '', '// School signature colours — use only for that school\'s material',
      '#let school-colours = (']
for k, v in sc.items():
    T.append(f'  {k}: {col(v)},')
T += [')', '', '// Neutrals (the design system uses neutral.8 as "black", neutral.9 is pure black)',
      '#let neutral-colours = (']
for k, v in neutral.items():
    key = k if not k[0].isdigit() else f'"{k}"'
    T.append(f'  {key}: {col(v)},')
T += [')', '', '// Tints: darker variants of the brand/school colours', '#let tint-colours = (']
for k, v in tint.items():
    T.append(f'  {k}: {col(v)},')
T += [')', '', '// Atomic type scale (pt)', '#let font-sizes = (']
for k in sorted(fs, key=lambda x: int(x)):
    T.append(f'  "{k}": {pt(fs[k])}pt,')
T += [')', '', '#let line-heights = (']
for k in sorted(lh, key=lambda x: int(x)):
    T.append(f'  "{k}": {pt(lh[k])}pt,')
T += [')', '', '#let letter-spacings = (']
for k in sorted(ls, key=lambda x: int(x)):
    T.append(f'  "{k}": {pt(ls[k])}pt,')
T += [')', '', '// Spacing scale (pt)', '#let spacing = (']
for k in sorted(dim, key=lambda x: int(x)):
    T.append(f'  "{k}": {pt(dim[k])}pt,')
T += [')', '', '// Composite type styles, desktop values (the web "media:desktop" tier,',
     '// which is the right reference for a full-screen slide).',
     '#let type-styles = (']
for group in ('title', 'body'):
    T.append(f'  {group}: (')
    for name, s in typo[group].items():
        d = s.get('desktop') or s
        T.append(f'    {name.replace("-", "_")}: (size: {d["size-pt"]:g}pt, leading: {d["leading-pt"]:g}pt, '
                 f'tracking: {d.get("tracking-pt", s["tracking-pt"]):g}pt, weight: "{s["weight"]}"),')
    T.append('  ),')
T += [')', '', '// Aspect ratios from the tokens (hd = the slide canvas)', '#let aspects = (']
for k, v in strip(base['aspect']).items():
    expr = resolve(v['$value']).replace(' / ', ' / ')
    T.append(f'  {k}: {expr},')
T.append(')')
dest = os.path.abspath(os.path.join(HERE, '..', '..', 'theme', 'tokens.typ'))
open(dest, 'w').write('\n'.join(T) + '\n')
print(f'notes/design-tokens.md + {os.path.relpath(dest, os.path.join(HERE,"..",".."))}')
print(f'  {len(bc)} brand, {len(sc)} school, {len(neutral)} neutral, {len(tint)} tint colours')
print(f'  {sum(len(v) for v in typo.values())} composite type styles')
